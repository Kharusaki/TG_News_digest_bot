"""Тексты справки: команды, расписание, вшитые и пользовательские источники."""

from __future__ import annotations

from sources import builtin_sources

TOPIC_NAMES = {
    "news": "Новости отрасли",
    "jobs": "Вакансии",
    "tech": "Технологии",
    "msfo": "Аудит и МСФО",
}


def builtin_sources_text() -> str:
    """Список вшитых лент, сгенерированный из фактических адресов кода."""
    lines = ["<b>Вшитые источники</b> (RSS/JSON, без HTML-парсинга):"]
    for topic, pairs in builtin_sources().items():
        names = ", ".join(f"{name} ({domain})" for name, domain in pairs)
        lines.append(f"• {TOPIC_NAMES.get(topic, topic)}: {names}")
    return "\n".join(lines)


